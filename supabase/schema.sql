create or replace function public.reorder_training_quests(p_order uuid[])
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_count integer;
  v_item record;
  v_old_order integer;
begin
  if v_user_id is null then
    raise exception 'Authentication is required to reorder quests.';
  end if;
  perform 1 from public.training_programs where user_id = v_user_id for update;

  select count(*) into v_count
  from public.training_quests
  where user_id = v_user_id;

  if v_count <> 10
     or coalesce(array_length(p_order, 1), 0) <> 10
     or (select count(distinct id) from unnest(p_order) as ids(id)) <> 10 then
    raise exception 'The order must contain each of the ten quests exactly once.';
  end if;

  for v_item in
    select id, ordinality::integer as new_order
    from unnest(p_order) with ordinality as requested(id, ordinality)
  loop
    select sort_order into v_old_order
    from public.training_quests
    where id = v_item.id and user_id = v_user_id;

    if not found then
      raise exception 'The order contains a quest that does not belong to this user.';
    end if;

    if exists (
      select 1 from public.training_quests
      where id = v_item.id and user_id = v_user_id and status <> 'planned'
    ) and v_old_order <> v_item.new_order then
      raise exception 'A started or completed quest cannot be moved.';
    end if;
  end loop;

  update public.training_quests
  set sort_order = sort_order + 10
  where user_id = v_user_id;

  update public.training_quests quest
  set sort_order = requested.new_order
  from (
    select id, ordinality::smallint as new_order
    from unnest(p_order) with ordinality as requested(id, ordinality)
  ) requested
  where quest.id = requested.id and quest.user_id = v_user_id;
end;
$$;

create or replace function public.rename_training_quest(
  p_quest_id uuid,
  p_name text,
  p_description text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication is required to edit quests.';
  end if;
  if length(trim(p_name)) = 0 then
    raise exception 'Quest name cannot be empty.';
  end if;
  perform 1 from public.training_programs where user_id = auth.uid() for update;

  update public.training_quests
  set name = trim(p_name), description = coalesce(p_description, '')
  where id = p_quest_id and user_id = auth.uid() and status = 'planned';

  if not found then
    raise exception 'Only a not-yet-started quest can be edited.';
  end if;
end;
$$;

create or replace function public.start_training_quest(p_quest_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_first_planned uuid;
begin
  if v_user_id is null then
    raise exception 'Authentication is required to start a quest.';
  end if;
  perform public.initialize_training_program();
  perform 1 from public.training_programs where user_id = v_user_id for update;

  if exists (select 1 from public.training_quests where user_id = v_user_id and status = 'active') then
    raise exception 'Finish the active quest before starting another.';
  end if;

  select id into v_first_planned
  from public.training_quests
  where user_id = v_user_id and status = 'planned'
  order by sort_order
  limit 1;

  if v_first_planned is distinct from p_quest_id then
    raise exception 'Start the next quest in the current order.';
  end if;

  update public.training_quests
  set status = 'active', started_at = current_date
  where id = p_quest_id and user_id = v_user_id and status = 'planned';

  update public.training_programs
  set active_quest_id = p_quest_id, updated_at = now()
  where user_id = v_user_id;
end;
$$;

create or replace function public.log_skate_practice(
  p_session_date date,
  p_skate_minutes integer,
  p_focused_minutes integer,
  p_notes text default ''
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_log_id uuid;
  v_quest public.training_quests%rowtype;
  v_next_quest_id uuid;
  v_chunk integer;
  v_remaining integer := p_focused_minutes;
begin
  if v_user_id is null then
    raise exception 'Authentication is required to log skate practice.';
  end if;
  if p_session_date is null or p_skate_minutes is null or p_focused_minutes is null
     or p_skate_minutes <= 0 or p_focused_minutes < 0 or p_focused_minutes > p_skate_minutes then
    raise exception 'Enter a valid date, positive skate minutes, and focused minutes no greater than skate minutes.';
  end if;

  perform public.initialize_training_program();
  perform 1 from public.training_programs where user_id = v_user_id for update;

  if p_focused_minutes > 0 and not exists (
    select 1 from public.training_quests where user_id = v_user_id and status = 'active'
  ) then
    raise exception 'Start the next quest before logging focused minutes.';
  end if;

  if exists (
    select 1 from public.training_programs
    where user_id = v_user_id and accumulated_focus_hours * 60 + p_focused_minutes > 60000
  ) then
    raise exception 'The 1,000-hour focused-practice target is already complete.';
  end if;

  insert into public.skate_practice_logs (user_id, session_date, skate_minutes, focused_minutes, notes)
  values (v_user_id, p_session_date, p_skate_minutes, p_focused_minutes, coalesce(p_notes, ''))
  returning id into v_log_id;

  while v_remaining > 0 loop
    select * into v_quest
    from public.training_quests
    where user_id = v_user_id and status = 'active'
    limit 1;

    if not found then
      select id into v_next_quest_id
      from public.training_quests
      where user_id = v_user_id and status = 'planned'
      order by sort_order
      limit 1;

      if v_next_quest_id is null then
        raise exception 'No unfinished season remains for focused practice.';
      end if;

      update public.training_quests
      set status = 'active', started_at = p_session_date
      where id = v_next_quest_id and user_id = v_user_id;
      update public.training_programs
      set active_quest_id = v_next_quest_id
      where user_id = v_user_id;

      select * into v_quest
      from public.training_quests
      where id = v_next_quest_id and user_id = v_user_id;
    end if;

    v_chunk := least(v_remaining, v_quest.target_focus_minutes - v_quest.focused_minutes);

    update public.training_quests
    set focused_minutes = focused_minutes + v_chunk,
        status = case when focused_minutes + v_chunk >= target_focus_minutes then 'completed' else 'active' end,
        completed_at = case when focused_minutes + v_chunk >= target_focus_minutes then now() else null end
    where id = v_quest.id;

    insert into public.training_focus_allocations (user_id, practice_log_id, quest_id, focused_minutes)
    values (v_user_id, v_log_id, v_quest.id, v_chunk);

    update public.training_programs
    set accumulated_focus_hours = accumulated_focus_hours + v_chunk::numeric / 60,
        active_quest_id = case when v_quest.focused_minutes + v_chunk >= v_quest.target_focus_minutes then null else v_quest.id end,
        updated_at = now()
    where user_id = v_user_id;

    v_remaining := v_remaining - v_chunk;
  end loop;

  update public.training_programs
  set active_quest_id = (
    select id from public.training_quests
    where user_id = v_user_id and status = 'active'
    limit 1
  ), updated_at = now()
  where user_id = v_user_id;

  return v_log_id;
end;
$$;

create or replace function public.log_benchmark(
  p_quest_id uuid,
  p_metric text,
  p_value numeric,
  p_notes text,
  p_tested_at date
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
  v_order smallint;
begin
  if auth.uid() is null then
    raise exception 'Authentication is required to log a benchmark.';
  end if;
  if p_value < 0 or length(trim(p_metric)) = 0 then
    raise exception 'Enter a benchmark name and a non-negative result.';
  end if;

  select sort_order into v_order
  from public.training_quests
  where id = p_quest_id and user_id = auth.uid();
  if not found then
    raise exception 'The benchmark must belong to one of your seasons.';
  end if;

  insert into public.benchmark_logs (user_id, quest_id, season_order, metric, value, notes, tested_at)
  values (auth.uid(), p_quest_id, v_order, trim(p_metric), p_value, coalesce(p_notes, ''), p_tested_at)
  returning id into v_id;
  return v_id;
end;
$$;

