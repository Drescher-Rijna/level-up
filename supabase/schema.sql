create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Skater',
  skating_start_date date not null default current_date,
  created_at timestamptz not null default now()
);

create table if not exists public.tasks (
  id text primary key,
  name text not null,
  description text not null default '',
  stat text not null check (stat in ('skill', 'body', 'mind', 'discipline', 'recovery', 'character')),
  xp integer not null check (xp > 0),
  active boolean not null default true,
  frequency text not null default 'daily' check (frequency = 'daily'),
  created_at timestamptz not null default now()
);

create table if not exists public.daily_completions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  task_id text not null references public.tasks(id) on delete restrict,
  completion_date date not null,
  xp_awarded integer not null check (xp_awarded > 0),
  completed_at timestamptz not null default now(),
  unique (user_id, task_id, completion_date)
);

create table if not exists public.quests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  description text not null default '',
  target_hours numeric not null default 100 check (target_hours > 0),
  completed_hours numeric not null default 0 check (completed_hours >= 0),
  status text not null default 'active' check (status in ('active', 'completed')),
  started_at date not null default current_date,
  completed_at timestamptz,
  completion_bonus_xp integer not null default 2000 check (completion_bonus_xp >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.skate_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  session_date date not null default current_date,
  hours numeric not null check (hours > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.quest_templates (
  id text primary key,
  name text not null,
  description text not null default '',
  target_hours numeric not null default 100 check (target_hours > 0),
  completion_bonus_xp integer not null default 2000 check (completion_bonus_xp >= 0),
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

